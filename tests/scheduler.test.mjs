test('queue pending/list views are read-only, bounded and oldest first',async t=>{
 const f=fixture(t),store=f.track(openStore(f.root,{scopeRef:'scope-A'}));
 const hooks={calls:0};
 const provider=createControlledProvider({resolveRoute:()=>routeA,invoke:async()=>{hooks.calls++;return extraction();}});
 const queue=createJobQueue(store,{provider,authorizeExecution:authorizeTestExecution});
 const first=queue.enqueue(job(store,{requestId:'first',sourceRef:'source-first'})),second=queue.enqueue(job(store,{requestId:'second',sourceRef:'source-second'}));
 const read=()=>{const db=new DatabaseSync(store.databasePath,{readOnly:true});try{return db.prepare('SELECT count(*) AS n FROM job_inputs').get().n;}finally{db.close();}};
 const budget=()=>{const db=new DatabaseSync(join(f.root,'authority.sqlite'),{readOnly:true});try{return db.prepare('SELECT coalesce(sum(requests),0) AS n FROM daily_budget').get().n;}finally{db.close();}};
 const before={inputs:read(),budget:budget()};
 assert.deepEqual(queue.pending({limit:1}).map(entry=>entry.jobId),[first.jobId]);
 assert.deepEqual(queue.pending().map(entry=>entry.jobId),[first.jobId]);
 assert.deepEqual(queue.list({state:'queued',limit:10}).map(entry=>entry.jobId),[first.jobId,second.jobId]);
 assert.deepEqual(queue.list({limit:10}).map(entry=>entry.jobId),[first.jobId,second.jobId]);
 assert.deepEqual(queue.list({state:'completed'}),[]);
 assert.equal(queue.get(first.jobId).state,'queued');
 assert.throws(()=>queue.pending({limit:0}),/Invalid/);
 assert.throws(()=>queue.list({state:'bogus'}),/Invalid/);
 assert.deepEqual({inputs:read(),budget:budget()},before);
 assert.equal(hooks.calls,0);
});
