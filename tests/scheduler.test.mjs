test('stop aborts the current run, is idempotent and stops further polling',async t=>{
 const h=setup(t,{scheduler:{jobTimeoutMs:30000}}),store=scopeStore(h),queue=scopeQueue(h),pending=latch(),started=latch();
 h.hooks.invoke=async()=>{started.resolve();return pending.promise;};
 h.scheduler.start();
 const current=queue.enqueue(job(store));
 const running=h.scheduler.tick();
 await started.promise;
 const controllerSignal=h.hooks.requests[0].signal;
 assert.equal(controllerSignal.aborted,false);
 const receipt=await h.scheduler.stop();
 assert.equal(receipt.state,'stopped');assert.equal(receipt.remoteStopConfirmed,false);
 assert.equal(controllerSignal.aborted,true);
 const second=await h.scheduler.stop();
 assert.equal(second.state,'stopped');assert.equal(second.remoteStopConfirmed,false);
 await running;
 assert.equal(queue.get(current.jobId).state,'outcome_unknown');
 const later=queue.enqueue(job(store,{requestId:'later',sourceRef:'source-later'}));
 const stopped=await h.scheduler.tick();
 assert.equal(stopped.state,'stopped');
 await new Promise(resolve=>setTimeout(resolve,120));
 assert.equal(h.hooks.calls,1);assert.equal(queue.get(later.jobId).state,'queued');
});
